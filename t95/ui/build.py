#!/usr/bin/env python3
"""Puts apcbox.css and apcbox.js into one file, apcbox.html, which the
bridge serves at /apcbox. Run after editing either:  python3 t95/ui/build.py
(--check: exit 1 if apcbox.html is out of date; the bridge tests run it)"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
css = open(os.path.join(here, "apcbox.css")).read()
js = open(os.path.join(here, "apcbox.js")).read()
assert "</script" not in js and "</style" not in css
import shutil, subprocess
if shutil.which("node"):    # a syntax error would leave the T95 with a blank page
    r = subprocess.run(["node", "-e", "new Function(require('fs').readFileSync(process.argv[1],'utf8'))", os.path.join(here, "apcbox.js")],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit("apcbox.js doesn't parse:\n" + r.stderr[:600])
html = """<!doctype html>
<!-- Generated by t95/ui/build.py from apcbox.css and apcbox.js: edit those -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<title>ApcBox</title>
<style>
%s</style>
</head>
<body>
<div class="app">
<div class="top"></div>
<div id="view"></div>
<div class="tabs" id="tabs"></div>
</div>
<script>
%s</script>
</body>
</html>
""" % (css, js)
out = os.path.join(here, "apcbox.html")
if "--check" in sys.argv:
    sys.exit(0 if os.path.exists(out) and open(out).read() == html else 1)
open(out, "w").write(html)
print("wrote", out, len(html), "bytes")
